/// A replacement effect that modifies an event before it happens.
///
/// Replacement effects follow rule 614: "If [event], [modified event] instead."
/// Examples: "If a creature would die, exile it instead."
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ReplacementEffect {
    /// Unique ID.
    pub id: ObjectId,
    /// The source permanent/ability that generates this replacement.
    pub source_id: ObjectId,
    /// The controller of the source.
    pub controller: PlayerId,
    /// Which event type this replaces.
    pub replaces: crate::events::EventType,
    /// Human-readable description.
    pub description: String,
    /// How long this replacement effect lasts.
    pub duration: Duration,
    /// Whether this effect is still active.
    pub active: bool,
    /// The kind of replacement.
    pub replacement: ReplacementKind,
}

/// What kind of replacement to apply.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub enum ReplacementKind {
    /// Prevent the event entirely.
    Prevent,
    /// Exile instead of going to graveyard.
    ExileInstead,
    /// Modify the amount (e.g. double damage, prevent N damage).
    ModifyAmount { delta: i32 },
    /// Redirect to a different target.
    RedirectTarget { new_target: ObjectId },
    /// Enter the battlefield tapped.
    EnterTapped,
    /// Add counters when entering.
    EnterWithCounters { counter_type: String, count: u32 },
    /// Custom replacement.
    Custom(String),
}

/// Stores all active replacement effects.
#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct ReplacementEffects {
    effects: Vec<ReplacementEffect>,
}

impl ReplacementEffects {
    pub fn new() -> Self {
        Self::default()
    }

    /// Add a replacement effect.
    pub fn add(&mut self, effect: ReplacementEffect) {
        self.effects.push(effect);
    }

    /// Find all replacement effects that apply to a given event type.
    pub fn for_event(&self, event_type: crate::events::EventType) -> Vec<&ReplacementEffect> {
        self.effects
            .iter()
            .filter(|e| e.active && e.replaces == event_type)
            .collect()
    }

    /// Remove effects from a source.
    pub fn remove_from_source(&mut self, source_id: ObjectId) {
        self.effects.retain(|e| e.source_id != source_id);
    }

    /// Remove expired effects.
    pub fn remove_expired(&mut self, is_end_of_turn: bool) {
        self.effects.retain(|e| {
            if !e.active {
                return false;
            }
            match e.duration {
                Duration::EndOfTurn => !is_end_of_turn,
                _ => true,
            }
        });
    }

    pub fn len(&self) -> usize {
        self.effects.iter().filter(|e| e.active).count()
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::constants::{Duration, KeywordAbilities, Layer, SubLayer};

    #[test]
    fn boost_effect() {
        let source = ObjectId::new();
        let target = ObjectId::new();
        let controller = PlayerId::new();

        let effect = ContinuousEffect::boost_until_eot(source, controller, target, 2, 2, 0);

        assert_eq!(effect.layer, Layer::PTChanging);
        assert_eq!(effect.sub_layer, Some(SubLayer::ModifyPT7c));
        assert_eq!(effect.duration, Duration::EndOfTurn);
        assert!(effect.active);

        match &effect.modification {
            EffectModification::ModifyPowerToughness { power, toughness, .. } => {
                assert_eq!(*power, 2);
                assert_eq!(*toughness, 2);
            }
            _ => panic!("wrong modification type"),
        }
    }

    #[test]
    fn keyword_grant_effect() {
        let source = ObjectId::new();
        let target = ObjectId::new();
        let controller = PlayerId::new();

        let effect = ContinuousEffect::grant_keyword_until_eot(
            source,
            controller,
            target,
            KeywordAbilities::FLYING,
            1,
        );

        assert_eq!(effect.layer, Layer::AbilityAddingRemoving);
        assert_eq!(effect.duration, Duration::EndOfTurn);
    }

    #[test]
    fn continuous_effects_manager() {
        let mut mgr = ContinuousEffects::new();
        let source = ObjectId::new();
        let target = ObjectId::new();
        let controller = PlayerId::new();

        let ts = mgr.next_timestamp();
        mgr.add(ContinuousEffect::boost_until_eot(source, controller, target, 1, 1, ts));

        let ts = mgr.next_timestamp();
        mgr.add(ContinuousEffect::grant_keyword_until_eot(
            source, controller, target, KeywordAbilities::TRAMPLE, ts,
        ));

        assert_eq!(mgr.len(), 2);

        let pt_effects = mgr.effects_for_layer(Layer::PTChanging);
        assert_eq!(pt_effects.len(), 1);

        let kw_effects = mgr.effects_for_layer(Layer::AbilityAddingRemoving);
        assert_eq!(kw_effects.len(), 1);

        // End of turn: remove all effects
        mgr.remove_expired(true);
        assert_eq!(mgr.len(), 0);
    }

    #[test]
    fn timestamp_ordering() {
        let mut mgr = ContinuousEffects::new();
        let source = ObjectId::new();
        let target = ObjectId::new();
        let controller = PlayerId::new();

        // Add effects with different timestamps
        let ts1 = mgr.next_timestamp();
        mgr.add(ContinuousEffect::boost_until_eot(source, controller, target, 1, 1, ts1));

        let ts2 = mgr.next_timestamp();
        mgr.add(ContinuousEffect::boost_until_eot(source, controller, target, 2, 2, ts2));

        let effects = mgr.effects_for_layer(Layer::PTChanging);
        assert_eq!(effects.len(), 2);
        // Should be ordered by timestamp
        assert!(effects[0].timestamp < effects[1].timestamp);
    }

    #[test]
    fn remove_from_source() {
        let mut mgr = ContinuousEffects::new();
        let source1 = ObjectId::new();
        let source2 = ObjectId::new();
        let target = ObjectId::new();
        let controller = PlayerId::new();

        mgr.add(ContinuousEffect::boost_until_eot(source1, controller, target, 1, 1, 0));
        mgr.add(ContinuousEffect::boost_until_eot(source2, controller, target, 2, 2, 1));

        assert_eq!(mgr.len(), 2);
        mgr.remove_from_source(source1);
        assert_eq!(mgr.len(), 1);
    }

    #[test]
    fn replacement_effects() {
        let mut replacements = ReplacementEffects::new();

        let source = ObjectId::new();
        let controller = PlayerId::new();

        replacements.add(ReplacementEffect {
            id: ObjectId::new(),
            source_id: source,
            controller,
            replaces: crate::events::EventType::Dies,
            description: "If this creature would die, exile it instead.".to_string(),
            duration: Duration::WhileOnBattlefield,
            active: true,
            replacement: ReplacementKind::ExileInstead,
        });

        let matching = replacements.for_event(crate::events::EventType::Dies);
        assert_eq!(matching.len(), 1);

        let non_matching = replacements.for_event(crate::events::EventType::DamagePlayer);
        assert_eq!(non_matching.len(), 0);
    }
}
